FIRST, LAST = 32, 126


def columns(rows):
    out = []
    for c in range(5):
        bits = 0
        for r in range(7):
            if rows[r][c] != ' ':
                bits |= (1 << r)
        out.append(bits)
    return out


def main():
    hexstr = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        rows = G.get(ch)
        if rows is None:
            rows = G.get(ch.upper())
        if rows is None:
            rows = G[' ']
        for b in columns(rows):
            hexstr.append("%02x" % b)
    s = "".join(hexstr)
    # 95 glyphs x 5 bytes x 2 hex chars
    assert len(s) == (LAST - FIRST + 1) * 10, len(s)
    chunks = [s[i:i + 100] for i in range(0, len(s), 100)]
    print("# %d glyphs, %d bytes" % (LAST - FIRST + 1, (LAST - FIRST + 1) * 5))
    for i, c in enumerate(chunks):
        print('fnt_hex_%d = strbuf("%s")' % (i, c))
    with open("font_hex.txt", "w") as f:
        for c in chunks:
            f.write(c + "\n")
    print("chunks:", len(chunks))


if __name__ == "__main__":
    main()
