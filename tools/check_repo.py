#!/usr/bin/env python3
"""check_repo.py — repository hygiene checks for OncoPattern.

These are the checks that can run anywhere, without the TECH toolchain: is the
tree publishable?  No build output tracked, no CRLF where a POSIX shell will
choke, no IMPORT pointing at a module that does not exist, no relative link
that 404s on GitHub.

The certificate suite (`tools/runtests`) is the real correctness gate and is
run separately — by `make test`, and by the `certificates` job in CI.

    python3 tools/check_repo.py [--verbose]

Exit status 0 means every check passed.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# never walked: vcs metadata, staged copies, build output
SKIP_DIRS = {".git", "results", "dist", "build", "__pycache__", ".venv", "venv"}

TEXT_SUFFIXES = {
    ".tech", ".md", ".py", ".sh", ".yml", ".yaml", ".json", ".csv", ".vcf",
    ".cff", ".toml", ".cfg", ".txt", ".svg", ".html",
}

# the platform's own output formats: they belong in results/ and dist/, never
# in the source tree, because they are regenerated by one command
OUTPUT_SUFFIXES = {".tbc", ".tbin", ".techbin", ".bmp", ".ppm", ".tfs"}

EXTENSIONLESS_TEXT = {".gitignore", ".gitattributes", ".editorconfig",
                      "Makefile", "AUTHORS", "LICENSE"}

REQUIRED = [
    "README.md",
    "LICENSE",
    "AUTHORS",
    ".gitignore",
    ".gitattributes",
    ".editorconfig",
    "CITATION.cff",
    "CONTRIBUTING.md",
    "CODE_OF_CONDUCT.md",
    "SECURITY.md",
    "CHANGELOG.md",
    "Makefile",
    "tools/ocbuild",
    "tools/runtests",
    "tools/check_repo.py",
    ".github/workflows/ci.yml",
]

# .gitignore must exclude everything a run produces, or the tree becomes
# un-reviewable the first time someone commits after building
GITIGNORE_MUST_MATCH = ["results/", "dist/", "*.tbc", "*.bmp"]

# the legacy spelling of the company name; it must not creep back into the
# product, the documents or the licence header
FORBIDDEN = {"ESS-KS": "company name is 'ESS KS Life Tech', without the hyphen"}

VERBOSE = False
failures = []
checks = 0


def fail(message):
    failures.append(message)


def ok(label):
    global checks
    checks += 1
    if VERBOSE:
        print("ok    " + label)


def walk():
    """Every file in the tree that a checkout would contain."""
    for base, dirs, files in os.walk(ROOT):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            full = os.path.join(base, name)
            yield os.path.relpath(full, ROOT).replace(os.sep, "/"), full


def check_required_files():
    for rel in REQUIRED:
        if not os.path.exists(os.path.join(ROOT, rel)):
            fail("missing required file: " + rel)
    ok("required files present")


def check_no_output_in_tree():
    """Artefacts may exist on disk; what matters is whether git would track
    them, which is what `.gitignore` decides."""
    candidates = []
    for rel, full in walk():
        ext = os.path.splitext(rel)[1].lower()
        if ext in OUTPUT_SUFFIXES:
            candidates.append(rel)
        elif os.path.getsize(full) > 1024 * 1024:
            fail("file larger than 1 MiB (belongs in results/ or a release): "
                 + rel)

    ignored = set()
    if candidates and os.path.isdir(os.path.join(ROOT, ".git")):
        try:
            proc = subprocess.run(
                ["git", "-C", ROOT, "check-ignore", "--no-index", "--"]
                + candidates, capture_output=True, text=True)
            ignored = set(line.strip() for line in proc.stdout.splitlines())
        except OSError:
            ignored = set()

    for rel in candidates:
        if rel in ignored:
            continue
        if not os.path.isdir(os.path.join(ROOT, ".git")) and \
                rel.startswith(("scratch/", "results/", "dist/")):
            continue
        fail("generated artefact git would track: " + rel)
    ok("no generated artefacts or oversized files")


def check_line_endings():
    for rel, full in walk():
        ext = os.path.splitext(rel)[1].lower()
        if ext not in TEXT_SUFFIXES and os.path.basename(rel) not in EXTENSIONLESS_TEXT:
            continue
        try:
            with open(full, "rb") as fh:
                data = fh.read()
        except OSError as exc:
            fail("cannot read %s: %s" % (rel, exc))
            continue
        if b"\r\n" in data:
            fail("CRLF line ending (the WSL build and its fixtures need LF): "
                 + rel)
        if data and not data.endswith(b"\n") and ext in {".tech", ".md", ".py"}:
            fail("missing final newline: " + rel)
    ok("line endings are LF")


def tech_roots():
    """Checkouts of the TECH toolchain, in the order tools/ocbuild uses them."""
    candidates = [os.environ.get("TECH_ROOT", ""),
                  os.path.join(ROOT, "..", "..", "TECH"),
                  os.path.join(ROOT, "..", "TECH"),
                  os.path.join(ROOT, "TECH")]
    roots = []
    for cand in candidates:
        if cand and os.path.isfile(os.path.join(cand, "techc")):
            roots.append(os.path.normpath(cand))
    return roots


def check_imports():
    """Every IMPORT in a .tech module must resolve to a .tech file — either in
    this repository, or in the TECH checkout the platform builds against."""
    modules = [rel for rel, _ in walk() if rel.endswith(".tech")]
    if not modules:
        fail("no .tech sources found")
        return
    roots = tech_roots()
    toolchain_imports = 0
    for rel in modules:
        with open(os.path.join(ROOT, rel), "r", encoding="utf-8",
                  errors="replace") as fh:
            for lineno, line in enumerate(fh, 1):
                m = re.match(r"\s*IMPORT\s+([A-Za-z0-9_./-]+)\s*$", line)
                if not m:
                    continue
                target = m.group(1) + ".tech"
                # imports are written from the TECH root, which is the parent
                # of oncopattern/; stdlib and unvm live in the toolchain
                places = [os.path.join(ROOT, "oncopattern", target),
                          os.path.join(ROOT, target)]
                places += [os.path.join(root, target) for root in roots]
                if any(os.path.exists(p) for p in places):
                    if not os.path.exists(places[0]) and not os.path.exists(places[1]):
                        toolchain_imports += 1
                    continue
                if not roots and m.group(1).split("/")[0] in ("stdlib", "unvm"):
                    toolchain_imports += 1
                    continue
                fail("%s:%d imports missing module %s"
                     % (rel, lineno, m.group(1)))
    ok("every IMPORT resolves (%d modules, %d from the toolchain)"
       % (len(modules), toolchain_imports))


def check_certificates():
    path = os.path.join(ROOT, "tools", "runtests")
    if not os.path.exists(path):
        return
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    m = re.search(r"^TESTS=\"(.*)\"$", text, re.MULTILINE)
    if not m:
        fail("tools/runtests: cannot find the TESTS list")
        return
    names = m.group(1).split()
    for name in names:
        rel = "oncopattern/test/%s.tech" % name
        if not os.path.exists(os.path.join(ROOT, rel)):
            fail("tools/runtests names a certificate that does not exist: "
                 + rel)
    ok("%d certificates named by tools/runtests all exist" % len(names))


def check_tools():
    count = 0
    for rel, full in walk():
        if not rel.startswith("tools/") or not rel.endswith(".py"):
            continue
        count += 1
        with open(full, "rb") as fh:
            head = fh.readline()
        if not head.startswith(b"#!"):
            fail("python tool without a shebang: " + rel)
        try:
            with open(full, "rb") as fh:
                compile(fh.read(), rel, "exec")
        except SyntaxError as exc:
            fail("%s: %s" % (rel, exc))
    ok("%d python tools parse" % count)


def check_gitignore():
    path = os.path.join(ROOT, ".gitignore")
    if not os.path.exists(path):
        fail("missing .gitignore")
        return
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        lines = {line.strip() for line in fh}
    for pattern in GITIGNORE_MUST_MATCH:
        if pattern not in lines:
            fail(".gitignore no longer excludes " + pattern)
    ok(".gitignore excludes build and run output")


def check_markdown_links():
    docs = ["README.md", "CONTRIBUTING.md", "CODE_OF_CONDUCT.md", "SECURITY.md",
            "CHANGELOG.md", "datasets/README.md", "docs/README.md"]
    pattern = re.compile(r"\[[^\]]*\]\(([^)\s]+)\)")
    for rel in docs:
        path = os.path.join(ROOT, rel)
        if not os.path.exists(path):
            continue
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        in_fence = False
        for lineno, line in enumerate(text.splitlines(), 1):
            if line.strip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            for target in pattern.findall(line):
                if re.match(r"[a-z]+://", target) or target.startswith("#"):
                    continue
                target = target.split("#")[0]
                if not target:
                    continue
                base = os.path.dirname(os.path.join(ROOT, rel))
                if not os.path.exists(os.path.normpath(os.path.join(base, target))):
                    fail("%s:%d links to missing file %s"
                         % (rel, lineno, target))
    ok("markdown links resolve")


def check_company_name():
    for rel, full in walk():
        if rel == "tools/check_repo.py":
            continue          # this file names the forbidden spelling itself
        ext = os.path.splitext(rel)[1].lower()
        if ext not in TEXT_SUFFIXES:
            continue
        try:
            with open(full, "r", encoding="utf-8", errors="replace") as fh:
                text = fh.read()
        except OSError:
            continue
        for bad, why in FORBIDDEN.items():
            if bad in text:
                fail("%s contains %r — %s" % (rel, bad, why))
    ok("company name is spelled 'ESS KS Life Tech'")


def main():
    global VERBOSE
    VERBOSE = "--verbose" in sys.argv[1:]
    check_required_files()
    check_no_output_in_tree()
    check_line_endings()
    check_imports()
    check_certificates()
    check_tools()
    check_gitignore()
    check_markdown_links()
    check_company_name()

    print("")
    for message in failures:
        print("FAIL  " + message)
    if failures:
        print("\n%d check(s) failed, %d passed" % (len(failures), checks))
        return 1
    print("%d checks passed — the tree is publishable" % checks)
    return 0


if __name__ == "__main__":
    sys.exit(main())
